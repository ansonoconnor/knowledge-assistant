/******************************************************************************
 * Authorization integration-test baseline
 *
 * Recreates the minimum schema that existed before authorization migrations
 * 001 and 002. The test harness applies the real committed migrations after
 * this fixture.
 ******************************************************************************/

begin;

create extension if not exists vector
with schema public;

create table public.organizations (
  id text primary key,
  name text not null,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.organization_memberships (
  organization_id text not null
    references public.organizations(id)
    on delete cascade,
  user_id uuid not null
    references auth.users(id)
    on delete cascade,
  role text not null default 'member'
    check (
      role = any (
        array[
          'member'::text,
          'manager'::text,
          'admin'::text
        ]
      )
    ),
  created_at timestamptz not null default now(),
  primary key (
    organization_id,
    user_id
  )
);

alter table public.organization_memberships
  enable row level security;

create policy
  "Authenticated users can view own organization memberships"
on public.organization_memberships
for select
to authenticated
using (
  user_id = auth.uid()
);

create table public.knowledge_chunks (
  id bigint generated by default as identity
    primary key,
  title text,
  chunk_text text,
  embedding vector(1536),
  created_at timestamptz default now(),
  representation_id text
);

insert into public.organizations (
  id,
  name
)
values
  (
    'org-momentum-co',
    'Organization A'
  ),
  (
    'org-isolation-b',
    'Organization B'
  );

insert into public.knowledge_chunks (
  title,
  chunk_text
)
values (
  'Existing Knowledge',
  'Existing pre-migration knowledge'
);

create function public.match_chunks(
  query_embedding vector,
  match_threshold double precision,
  match_count integer
)
returns table (
  id bigint,
  title text,
  chunk_text text,
  similarity double precision
)
language sql
stable
as $function$
  select
    chunk.id,
    chunk.title,
    chunk.chunk_text,
    1 - (
      chunk.embedding <=>
      query_embedding
    ) as similarity
  from public.knowledge_chunks chunk
  where chunk.embedding is not null
    and 1 - (
      chunk.embedding <=>
      query_embedding
    ) > match_threshold
  order by
    chunk.embedding <=>
    query_embedding
  limit match_count;
$function$;

create function public.match_chunks(
  query_embedding vector,
  match_count integer default 5
)
returns table (
  id bigint,
  title text,
  chunk_text text,
  similarity double precision
)
language sql
as $function$
  select
    chunk.id,
    chunk.title,
    chunk.chunk_text,
    1 - (
      chunk.embedding <=>
      query_embedding
    ) as similarity
  from public.knowledge_chunks chunk
  order by
    chunk.embedding <=>
    query_embedding
  limit match_count;
$function$;

grant usage
on schema public
to anon, authenticated, service_role;

grant select
on public.organizations,
   public.organization_memberships
to authenticated;

grant select, insert
on public.knowledge_chunks
to authenticated;

grant all privileges
on public.organizations,
   public.organization_memberships,
   public.knowledge_chunks
to service_role;

grant usage, select
on all sequences in schema public
to authenticated, service_role;

commit;
